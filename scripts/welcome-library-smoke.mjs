import { chromium } from 'playwright'
import assert from 'node:assert/strict'

const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(process.env.PINAX_SMOKE_URL || 'http://127.0.0.1:5173')
  await page.waitForSelector('.library-empty')
  await page.screenshot({ path: '/tmp/pinax-library-empty.png' })
  const seeded = await page.evaluate(async () => {
    const repo = await import('/src/services/writing/writingBooksRepository.js')
    const books = ['三体同人', '铅青时分', '长夜之后：一个关于失落星球与遥远故乡的故事', 'Book 2', 'Book 10'].map((title, index) => ({
      id: `library-smoke-${index}`, title, createdAt: '2026-09-01T00:00:00Z', updatedAt: `2026-09-${String(16 - index).padStart(2, '0')}T00:00:00Z`,
      chapters: [{ id: `chapter-${index}`, title: '第一章', content: '', wordCount: 3332 + index }]
    }))
    if (!repo.saveWritingBooksDurable(books).ok) throw new Error('seed failed')
    return JSON.stringify(repo.loadWritingBooks())
  })
  await page.waitForSelector('[data-test="library-book"]')
  assert.equal(await page.locator('[data-test="library-book"]').count(), 5)
  assert.match(await page.locator('[data-test="welcome-continue-book"]').getAttribute('href'), /bookId=library-smoke-0/)
  for (const width of [1440, 900, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.screenshot({ path: `/tmp/pinax-library-${width}.png` })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `overflow ${width}`)
  }
  await page.getByRole('searchbox', { name: '搜索书名' }).fill('三体')
  assert.equal(await page.locator('[data-test="library-book"]').count(), 1)
  await page.getByRole('searchbox').fill('没有这本书')
  await page.getByRole('button', { name: '清除搜索' }).click()
  assert.equal(await page.locator('[data-test="library-book"]').count(), 5)
  assert(await page.getByRole('searchbox').evaluate(el => el === document.activeElement))
  await page.getByRole('combobox', { name: '书稿排序' }).selectOption('title')
  const titles = await page.locator('.book-card h3').allTextContents()
  assert.deepEqual(titles, [...titles].sort((a, b) => a.localeCompare(b, 'zh-CN', { numeric: true })))
  await page.getByRole('button', { name: '列表', exact: true }).click()
  await page.screenshot({ path: '/tmp/pinax-library-list-mobile.png' })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  assert.equal(await page.evaluate(async () => JSON.stringify((await import('/src/services/writing/writingBooksRepository.js')).loadWritingBooks())), seeded)
  await page.reload()
  await page.waitForSelector('[data-test="library-book"]')
  assert.equal(await page.locator('[data-test="library-book"]').count(), 5)
  await page.locator('[data-test="library-book"]').first().click()
  await page.waitForURL(/bookId=library-smoke-0/)
  await page.locator('.ProseMirror').first().waitFor()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.locator('.ProseMirror').first().fill('标签往返时，这段尚未等到自动保存的文字也不能丢失。')
  await page.locator('.ws-tab[data-tab-id="pinax-home"]').click()
  await page.waitForSelector('.library-main')
  assert.equal(await page.locator('.ws-tab').count(), 2)
  assert.equal(await page.locator('.ws-tab[data-tab-id="pinax-home"]').getAttribute('aria-current'), 'true')
  await page.locator('.ws-tab[title="三体同人"]').focus()
  await page.keyboard.press('Enter')
  await page.locator('.ProseMirror').first().waitFor()
  assert.match(await page.locator('.ProseMirror').first().innerText(), /不能丢失/)
  await page.locator('.ws-tab[data-tab-id="pinax-home"]').click()
  await page.waitForSelector('.library-main')
  await page.getByRole('link', { name: '打开《铅青时分》', exact: true }).click()
  await page.waitForURL(/bookId=library-smoke-1/)
  await page.locator('.ws-tab[data-tab-id="pinax-home"]').click()
  await page.waitForSelector('.library-main')
  await page.getByRole('button', { name: '关闭 铅青时分', exact: true }).click()
  assert.equal(await page.locator('.ws-tab[data-tab-id="pinax-home"]').getAttribute('aria-current'), 'true')
  assert.equal(await page.locator('[data-test="library-book"]').count(), 5)
  // AppShell uses out-in route transitions. Wait for the returning view to own
  // the DOM before changing its ephemeral project selection.
  await page.waitForFunction(() => !document.querySelector('.page-route-enter-active, .page-route-leave-active, .page-layer-enter-active, .page-layer-leave-active'))
  await page.getByRole('combobox', { name: '工具所属作品' }).selectOption('library-smoke-1')
  await page.waitForFunction(() => document.querySelector('.library-sidebar a[href*="settings/structured"]')?.getAttribute('href')?.includes('bookId=library-smoke-1')).catch(async error => {
    console.error(await page.evaluate(() => ({ url: location.href, select: document.querySelector('.library-sidebar select')?.value, sidebarCount: document.querySelectorAll('.library-sidebar').length, options: [...document.querySelectorAll('.library-sidebar option')].map(el => el.value) })))
    throw error
  })
  assert.match(await page.getByRole('link', { name: '人物与设定', exact: true }).getAttribute('href'), /bookId=library-smoke-1/)
  await page.getByRole('link', { name: '灵感素材', exact: true }).click()
  await page.waitForURL(/materials.*bookId=library-smoke-1/)
  await page.locator('.ws-tab[data-tab-id="pinax-home"]').click()
  await page.waitForSelector('.library-main')
  await page.reload()
  await page.waitForSelector('.library-main')
  assert.equal(await page.locator('.ws-tab').count(), 3)
  const summary = page.locator('summary[aria-label="新建作品选项"]')
  await summary.click()
  assert(await page.getByRole('link', { name: '空白小说', exact: true }).isVisible())
  await summary.press('Escape')
  assert.equal(await page.locator('.library-quick-actions details').getAttribute('open'), null)
  await page.screenshot({ path: '/tmp/pinax-home-v2-desktop.png' })
  await page.setViewportSize({ width: 390, height: 1000 })
  await page.getByRole('button', { name: '展开功能导航' }).click()
  assert(await page.getByRole('link', { name: '世界地图', exact: true }).isVisible())
  await page.screenshot({ path: '/tmp/pinax-home-v2-mobile-nav.png' })
  await page.getByRole('button', { name: '展开功能导航' }).click()
  await page.screenshot({ path: '/tmp/pinax-home-v2-mobile.png' })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  assert.equal(errors.length, 0, errors.join('\n'))
  console.log('Library smoke: empty / 5 books / search / sort / grid-list / focus / unchanged data / reload / 3 viewports / pinned home / keyboard tabs / immediate editor save on return / background close / project navigation / menu Escape / mobile navigation OK')
} finally { await browser.close() }
